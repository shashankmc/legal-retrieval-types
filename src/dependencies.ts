// Backend-dependency helpers for retrieval methods: what a method still needs
// before it can run, and a scaffold describing how to configure it.

import type { MethodDescriptor, DependencyDescriptor } from './retrieval.js'

/** The dependencies a method cannot run without (optional ones excluded). */
export function requiredDependencies(method: MethodDescriptor): DependencyDescriptor[] {
  return (method.dependencies ?? []).filter((dep) => dep.optional !== true)
}

/**
 * The dependencies blocking a method, given the availability a host probe (or
 * the method list) reported. An unknown availability is not treated as unmet.
 */
export function unmetDependencies(method: MethodDescriptor): DependencyDescriptor[] {
  if (method.available !== false) return []
  return requiredDependencies(method)
}

/** Human hint naming what a method needs, e.g. "Sentence-BERT model". */
export function dependencyHint(method: MethodDescriptor): string {
  return (method.dependencies ?? []).map((dep) => dep.label).join(', ')
}

/** The methods that declare at least one backend dependency. */
export function methodsWithDependencies(methods: MethodDescriptor[]): MethodDescriptor[] {
  return methods.filter((method) => (method.dependencies?.length ?? 0) > 0)
}

function toEnvKey(id: string): string {
  return id
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toUpperCase()
}

/**
 * A commented .env-style template listing every method's backend dependencies
 * and the config keys the service expects. Hosts show it so an operator can
 * stand up the backend a method needs.
 */
export function buildDependencyScaffold(methods: MethodDescriptor[]): string {
  const lines: string[] = [
    '# Backend configuration required by retrieval methods.',
    '# Fill in the values and give them to your service. Generated by legal-retrieval-types.',
    '',
  ]

  let any = false
  for (const method of methods) {
    const deps = method.dependencies ?? []
    if (deps.length === 0) continue
    any = true
    lines.push(`# Method: ${method.label} (${method.id})`)
    for (const dep of deps) {
      const optional = dep.optional ? ' (optional)' : ''
      const description = dep.description ? `: ${dep.description}` : ''
      lines.push(`#   - ${dep.label} [${dep.kind}]${optional}${description}`)
      const keys = dep.configKeys?.length ? dep.configKeys : [toEnvKey(dep.id)]
      for (const key of keys) lines.push(`${key}=`)
    }
    lines.push('')
  }

  if (!any) lines.push('# No method declares backend dependencies.')
  return lines.join('\n')
}
